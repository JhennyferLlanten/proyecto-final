package co.edu.uniquindio.clustering;

public class Union {

    public int grupoIzquierdo;
    public int grupoDerecho;
    public double altura;
    public int tamano;

    public Union(int grupoIzquierdo, int grupoDerecho, double altura, int tamano) {
        this.grupoIzquierdo = grupoIzquierdo;
        this.grupoDerecho = grupoDerecho;
        this.altura = altura;
        this.tamano = tamano;
    }
}
